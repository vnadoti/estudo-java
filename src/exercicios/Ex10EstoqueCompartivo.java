package exercicios;

import java.util.Scanner;

public class Ex10EstoqueCompartivo {
    public static void main() {
        int estoque = 15;

        System.out.println(estoque > 15);
        System.out.println(estoque < 20);
        System.out.println(estoque >= 15);
        System.out.println(estoque <= 15);
        System.out.println(estoque == 15);
        System.out.println(estoque != 0);
    }

}
